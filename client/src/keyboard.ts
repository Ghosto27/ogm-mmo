// Маппинг русских клавиш на английские (основные, строчные и заглавные)
const rusToEng: Record<string, string> = {
    'ф':'a','и':'b','с':'c','в':'d','у':'e','а':'f','п':'g','р':'h','ш':'i','о':'j',
    'л':'k','д':'l','ь':'m','т':'n','щ':'o','з':'p','й':'q','к':'r','ы':'s','е':'t',
    'г':'u','м':'v','ц':'w','ч':'x','н':'y','я':'z',
    'Ф':'A','И':'B','С':'C','В':'D','У':'E','А':'F','П':'G','Р':'H','Ш':'I','О':'J',
    'Л':'K','Д':'L','Ь':'M','Т':'N','Щ':'O','З':'P','Й':'Q','К':'R','Ы':'S','Е':'T',
    'Г':'U','М':'V','Ц':'W','Ч':'X','Н':'Y','Я':'Z'
};

/**
 * Если символ – русская буква, возвращает английский эквивалент в нижнем регистре.
 * Иначе возвращает символ в нижнем регистре.
 */
export function normalizeKey(key: string): string {
    const eng = rusToEng[key];
    return eng ? eng.toLowerCase() : key.toLowerCase();
}